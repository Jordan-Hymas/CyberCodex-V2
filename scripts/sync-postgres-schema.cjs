const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const source = fs.readFileSync(path.join(root, 'prisma/schema.prisma'), 'utf8');
const schema = '// GENERATED by npm run db:postgres:sync; edit prisma/schema.prisma, then regenerate.\n' + source.replace('provider = "sqlite"', 'provider = "postgresql"');
if (schema === '// GENERATED by npm run db:postgres:sync; edit prisma/schema.prisma, then regenerate.\n' + source) throw new Error('Expected SQLite source schema');
const target = path.join(root, 'prisma/postgresql/schema.prisma');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== schema) {
    console.error('PostgreSQL schema is stale. Run npm run db:postgres:sync and create a migration for model changes.');
    process.exit(1);
  }
} else fs.writeFileSync(target, schema);
